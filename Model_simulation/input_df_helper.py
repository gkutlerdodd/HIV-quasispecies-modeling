#!/usr/bin/env python3

# ------------------------------------------------------------------------------
# Script Name: input_df_helper.py
# Description: Helper script to generate a dataframe in the format for model_simulation.py.
#              Merges EvoEF outputs for receptor-binding and antibody-binding and computes ddG_receptor, ddG_Ab.
#
# Output: CSV containing one column per residue (first N columns), followed by sequence, ddG, ddG_Ab
#
# Author: Griffin Kutler Dodd
#
# Date Created: 2025-10-31
# Last Modified: 2025-10-31
#
# Requirements:
#   - This script is designed to be run using Python 3.13.5
#
# Usage:
#   Designed to be run from the commandline using python3 input_df_helper.py --receptor-df [receptor df] --antibody-df [antibody df] --out [output name]
#   Both input dataframes should be EvoEF predictions as generated by affinity_prediction_EvoEF.py
#
# ------------------------------------------------------------------------------

import pandas as pd
import argparse

def parse_args():
    """Read arguments from the CLI."""
    p = argparse.ArgumentParser(description="Compute receptor-binding ddG and antibody-binding ddG and save in a format compatible with model simulations.")
    p.add_argument("--receptor-df", required=True, help="CSV file with receptor binding affinities.")
    p.add_argument("--antibody-df", required=True, help="CSV file with antibody binding affinities.")
    p.add_argument("--out", required=True, help="Output name for merged dataframe.")
    p.add_argument("--wt-seq", default="DIRQH", help="WT sequence.")
    return p.parse_args()

def build_sequence_column(df, N):
    aa_cols = list(df.columns[:N])
    df = df.copy()
    df["sequence"] = df[aa_cols].astype(str).apply(lambda row: "".join(x.strip() for x in row), axis=1)
    return df

def compute_ddg(df, binding_col, wt_seq, out_name):
    wt_idx = df.loc[df["sequence"] == wt_seq]
    wt_binding = float(wt_idx.iloc[0][binding_col])
    df = df.copy()
    df[out_name] = df[binding_col].astype(float) - wt_binding
    return df

def main():
    args = parse_args()
    df_receptor = pd.read_csv(args.receptor_df)
    df_Ab = pd.read_csv(args.antibody_df)

    df_receptor = compute_ddg(build_sequence_column(df_receptor, len(args.wt_seq)), 'binding_energy', args.wt_seq, "ddG")
    df_Ab = compute_ddg(build_sequence_column(df_Ab, len(args.wt_seq)), 'binding_energy', args.wt_seq, "ddG_Ab")

    merged = pd.merge(df_receptor, df_Ab[["sequence", "ddG_Ab"]], on="sequence", how="inner").drop(columns=["binding_energy"])
    merged.to_csv(f"{args.out}.csv")

if __name__ == "__main__":
    main()




