#!/usr/bin/env python3
"""
Format a variant dataframe for model simulation using the output of prediction.py.
Output:
    CSV containing one column per residue (first N columns), followed by sequence, ddG, ddG_Ab

Usage:
    python3 -m src.preprocessing.variants_dataframe --receptor-df [receptor df] --antibody-df [antibody df] --wt-binding [energy] --out [output name]
    Both input dataframes should be EvoEF predictions as generated by affinity_prediction_EvoEF.py
    Since ddG_Ab is relative to the WT Ab, the binding energy of the WT seq-WT Ab needs to be inputted
"""


import pandas as pd
import argparse

def parse_args():
    """Read arguments from the CLI."""
    p = argparse.ArgumentParser(description="Compute receptor-binding ddG and antibody-binding ddG and save in a format compatible with model simulations.")
    p.add_argument("--receptor-df", required=True, help="CSV file with receptor binding affinities.")
    p.add_argument("--antibody-df", required=True, help="CSV file with antibody binding affinities.")
    p.add_argument("--wt-binding", type=float, required=True, help="Binding energy of the WT virus to the WT antibody.")
    p.add_argument("--out", required=True, help="Output name for merged dataframe.")
    p.add_argument("--wt-seq", default="DIRQH", help="WT sequence.")
    return p.parse_args()

def build_sequence_column(df, N):
    aa_cols = list(df.columns[:N])
    df = df.copy()
    df["sequence"] = df[aa_cols].astype(str).apply(lambda row: "".join(x.strip() for x in row), axis=1)
    return df

def compute_ddg(df, wt_seq, out_name, wt_binding=None):
    df = df.copy()
    if not wt_binding:
        wt_idx = df.loc[df["sequence"] == wt_seq]
        wt_binding = float(wt_idx.iloc[0]['binding_energy'])
    df[out_name] = df['binding_energy'].astype(float) - wt_binding
    return df

def main():
    args = parse_args()
    df_receptor = pd.read_csv(args.receptor_df)
    df_Ab = pd.read_csv(args.antibody_df)

    df_receptor = compute_ddg(build_sequence_column(df_receptor, len(args.wt_seq)), args.wt_seq, "ddG")
    df_Ab = compute_ddg(build_sequence_column(df_Ab, len(args.wt_seq)), args.wt_seq, "ddG_Ab", wt_binding=args.wt_binding)

    merged = pd.merge(df_receptor, df_Ab[["sequence", "ddG_Ab"]], on="sequence", how="inner").drop(columns=["binding_energy"])
    merged.to_csv(f"{args.out}.csv")

if __name__ == "__main__":
    main()




